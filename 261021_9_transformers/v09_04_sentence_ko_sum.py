from transformers import pipeline

# 1. 요약 파이프라인 (한국어 KoBART 요약 모델)
summerizer = pipeline("summarization", model="digit82/kobart-summarization")

# 2. 요약할 문장
text = """
부천시는 다음 달 1일부터 시민 누구나 이용할 수 있는 무료 공유 자전거 서비스를 전역으로 확대한다고 21일 밝혔다. 시는 지난해 중동과 상동 일대에서 시범 운영한 결과 하루 평균 이용 건수가 1,200건을 넘고 시민 만족도가 90%에 가깝게 나오자 서비스 지역을 시 전체로 넓히기로 했다. 이번 확대로 자전거 보관소는 기존 40곳에서 150곳으로 늘어나고, 자전거는 500대에서 2,000대로 늘어난다. 이용 요금은 처음 30분까지 무료이며, 이후 10분마다 200원이 부과된다. 시는 청소년과 65세 이상 어르신, 기초생활수급자에게는 연간 이용권을 반값에 제공할 계획이다. 이용 방법은 스마트폰 앱을 내려받아 본인 인증을 한 뒤, 보관소에 있는 자전거의 QR코드를 찍으면 된다. 반납은 어느 보관소에서든 가능하다. 시 관계자는 "출퇴근 시간대에 지하철역 주변 보관소에 자전거가 부족하다는 의견이 많았다"며 "역 주변에 보관소를 우선 늘리고, 이용 현황을 분석해 자전거를 시간대별로 재배치하겠다"고 말했다. 시는 또 자전거 도로가 끊긴 구간 12곳을 올해 안에 연결하고, 안전모 무료 대여 사업도 함께 추진할 방침이다. 시는 이번 사업으로 연간 이산화탄소 배출량이 약 800톤 줄어들 것으로 기대하고 있다.
"""

# 3. 요약 실행
summary = summerizer(
    text,
    min_length=20,  # 최소 토큰
    max_length=64,  # 최대 토큰 (한글 약 100자)
    do_sample=False,  # 매번 동일 결과 출력
)

# 4. 결과 확인
sum_text = summary[0]["summary_text"]
print(f"요약된 결과 : {sum_text}")
print(f"요약 글자 수 : {len(sum_text)}자")
